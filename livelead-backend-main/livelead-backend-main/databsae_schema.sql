CREATE DATABASE LIVELEAF_DB;

USE LIVELEAF_DB;

-- ==========================================
-- 1. USERS TABLE
-- ==========================================

CREATE TABLE USERS
(
    ID INT AUTO_INCREMENT PRIMARY KEY,

    NAME VARCHAR(100) NOT NULL,

    EMAIL VARCHAR(255) NOT NULL UNIQUE,

    PASSWORD VARCHAR(255) NOT NULL,

    CREATED_AT DATE NOT NULL DEFAULT (CURRENT_DATE),

    UPDATED_AT DATE NOT NULL DEFAULT (CURRENT_DATE)
);


-- ==========================================
-- 2. PLANTS TABLE
-- ==========================================

CREATE TABLE PLANTS
(
    PLANT_ID INT AUTO_INCREMENT PRIMARY KEY,

    SCIENTIFIC_NAME VARCHAR(150) NOT NULL,

    COMMON_NAME VARCHAR(100) NOT NULL,

    MAX_HEIGHT DOUBLE NOT NULL,

    LIGHT_REQUIREMENTS VARCHAR(100) NOT NULL,

    SOIL_PH_MAX DECIMAL(4,2) NOT NULL,

    SOIL_PH_MIN DECIMAL(4,2) NOT NULL,

    WATER_NEEDED VARCHAR(100) NOT NULL,

    OPTIMUM_SOIL_MOISTURE_PCT DECIMAL(5,2) NOT NULL,

    CRITICAL_DROUGHT_PCT DECIMAL(5,2) NOT NULL,

    -- newly added columns
    H_SOIL DECIMAL(5,2) NOT NULL, 
    
    L_SOIL DECIMAL(5,2) NOT NULL, 
    
    H_TEMP DECIMAL(5,2) NOT NULL, 
    
    L_TEMP DECIMAL(5,2) NOT NULL, 
    
    H_HUMI DECIMAL(5,2) NOT NULL, 
    
    L_HUMI DECIMAL(5,2) NOT NULL, 
    
    SENSOR_CHECK_INTERVAL_HRS INT NOT NULL,

    CONSTRAINT UQ_PLANTS_SCIENTIFIC_NAME
        UNIQUE (SCIENTIFIC_NAME),

    CONSTRAINT CHK_SOIL_PH
        CHECK (
            SOIL_PH_MIN >= 0
            AND SOIL_PH_MAX <= 14
            AND SOIL_PH_MIN <= SOIL_PH_MAX
        ),

    CONSTRAINT CHK_MAX_HEIGHT
        CHECK (MAX_HEIGHT > 0),

    CONSTRAINT CHK_SOIL_MOISTURE
        CHECK (OPTIMUM_SOIL_MOISTURE_PCT BETWEEN 0 AND 100),

    CONSTRAINT CHK_CRITICAL_DROUGHT
        CHECK (CRITICAL_DROUGHT_PCT BETWEEN 0 AND 100),

    -- new column constraints
    CONSTRAINT CHK_SOIL_MOISTURE_LIMITS
        CHECK (
            H_SOIL BETWEEN 0 AND 100 
            AND L_SOIL BETWEEN 0 AND 100 
            AND L_SOIL <= H_SOIL
        ),

    CONSTRAINT CHK_TEMP_LIMITS
        CHECK (L_TEMP <= H_TEMP),

    CONSTRAINT CHK_HUMIDITY_LIMITS
        CHECK (
            H_HUMI BETWEEN 0 AND 100 
            AND L_HUMI BETWEEN 0 AND 100 
            AND L_HUMI <= H_HUMI
        ),
        
    CONSTRAINT CHK_SENSOR_INTERVAL
        CHECK (SENSOR_CHECK_INTERVAL_HRS > 0)
);

-- ==========================================
-- 3. USER_PLANTS TABLE
-- ==========================================

CREATE TABLE USER_PLANTS
(
    USER_ID INT NOT NULL,

    PLANT_ID INT NOT NULL,

    GROWTH_STAGE VARCHAR(50) NOT NULL,

    CONSTRAINT PK_USER_PLANTS
        PRIMARY KEY (USER_ID, PLANT_ID),

    CONSTRAINT FK_USER_PLANTS_USERS
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_USER_PLANTS_PLANTS
        FOREIGN KEY (PLANT_ID)
        REFERENCES PLANTS(PLANT_ID)
        ON DELETE CASCADE
);